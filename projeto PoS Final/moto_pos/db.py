class DatabaseIntegrityError(Exception):
    """Backend-independent integrity constraint violation."""


class DatabaseConnection:
    def __init__(self, connection: Any, dialect: str, integrity_error: type[Exception]):
        self._connection = connection
        self.dialect = dialect
        self._integrity_error = integrity_error

    @property
    def in_transaction(self) -> bool:
        if self.dialect == "sqlite":
            return self._connection.in_transaction
        from psycopg.pq import TransactionStatus

        return self._connection.info.transaction_status != TransactionStatus.IDLE

    def execute(self, statement: str, parameters: tuple[Any, ...] = ()):
        if self.dialect == "postgresql":
            if statement.strip().upper() == "BEGIN IMMEDIATE":
                statement = "BEGIN"
            statement = statement.replace("?", "%s")
        try:
            return self._connection.execute(statement, parameters)
        except self._integrity_error as error:
            raise DatabaseIntegrityError(str(error)) from error

    def executescript(self, script: str) -> None:
        if self.dialect == "sqlite":
            self._connection.executescript(script)
            return
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)

    def close(self) -> None:
        self._connection.close()

    def __enter__(self) -> Self:
        return self

    def __exit__(self, exc_type, exc_value, traceback) -> bool:
        if exc_type is not None and self.in_transaction:
            self._connection.rollback()
        self.close()
        return False


def connect(target: str | Path | None = None) -> DatabaseConnection:
    configured = str(target) if target is not None else os.environ.get("DATABASE_URL", "")
    if configured.startswith(("postgres://", "postgresql://")):
        import psycopg
        from psycopg.rows import dict_row

        if configured.startswith("postgres://"):
            configured = "postgresql://" + configured.removeprefix("postgres://")
        connection = psycopg.connect(
            configured,
            autocommit=True,
            connect_timeout=10,
            row_factory=dict_row,
        )
        return DatabaseConnection(connection, "postgresql", psycopg.IntegrityError)
    if "://" in configured:
        raise RuntimeError("DATABASE_URL deve usar o esquema postgres:// ou postgresql://.")

    database_path = Path(configured) if configured else get_database_path()
    database_path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(database_path, timeout=10, isolation_level=None)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    connection.execute("PRAGMA journal_mode = WAL")
    return DatabaseConnection(connection, "sqlite", sqlite3.IntegrityError)


def initialize_database(target: str | Path | None = None) -> None:
    with connect(target) as connection:
        schema = POSTGRES_SCHEMA if connection.dialect == "postgresql" else SQLITE_SCHEMA
        connection.executescript(schema)
        username = os.environ.get("ADMIN_USERNAME", "admin").strip()
        password = os.environ.get("ADMIN_PASSWORD", "admin")
        if not username or len(username) > 80:
            raise RuntimeError("Defina ADMIN_USERNAME com entre 1 e 80 caracteres.")
        if len(password) < 12:
            raise RuntimeError("ADMIN_PASSWORD deve ter pelo menos 12 caracteres.")
        exists = connection.execute("SELECT 1 FROM users WHERE username = ?", (username,)).fetchone()
        if exists is None:
            connection.execute(
                "INSERT INTO users(username, password_hash) VALUES (?, ?)",
                (username, generate_password_hash(password)),
            )
